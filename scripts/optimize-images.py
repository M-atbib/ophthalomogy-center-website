"""Create WebP assets and image metadata for images used by the SvelteKit site.

Run from the repository root with: python scripts/optimize-images.py
Requires Pillow with WebP support. Archived PNG/JPEG sources are never changed or deleted.
"""

from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from pathlib import Path

from PIL import Image, ImageOps, features


ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "image-old/src/lib/assets/images"
OUTPUT_DIR = ROOT / "src/lib/assets/images"
ASSET_INDEX = ROOT / "src/lib/assets/index.ts"
APP_SOURCE = ROOT / "src"
OUTPUT_MODULE = ROOT / "src/lib/assets/image-data.ts"
STATE_FILE = ROOT / "src/lib/assets/images/.webp-generation-state.json"
INPUT_SUFFIXES = {".png", ".jpg", ".jpeg"}
RESPONSIVE_WIDTHS = (480, 960, 1600)
PHOTO_QUALITY = 88
MEDICAL_QUALITY = 94
ENCODER_METHOD = 4


def slug(stem: str) -> str:
    plain = unicodedata.normalize("NFKD", stem).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", plain.lower()).strip("-")


def active_webp_names() -> set[str]:
    """Find images imported by pages, components and active asset exports."""
    source_files = (
        path for path in APP_SOURCE.rglob("*")
        if path.suffix in {".svelte", ".ts", ".js", ".css"}
        and path not in {ASSET_INDEX, OUTPUT_MODULE}
    )
    code = "\n".join(path.read_text(encoding="utf-8") for path in source_files)
    names = set(re.findall(r"images/([^\s\"']+\.webp)", code))
    index = ASSET_INDEX.read_text(encoding="utf-8")
    for alias, name in re.findall(
        r"export\s*\{\s*default\s+as\s+(\w+)\s*\}\s*from\s*['\"]\$lib/assets/images/([^'\"]+\.webp)",
        index,
    ):
        if re.search(r"\b" + re.escape(alias) + r"\b", code):
            names.add(name)
    if not names:
        raise ValueError("No active WebP references found; refusing to clear image metadata")
    return names


def use_responsive_sizes(path: Path, width: int) -> bool:
    """Only multi-size UI images and very large article photos get variants."""
    name = path.stem.lower()
    return name.startswith(("home-", "about-")) or ("-img" in name and width >= 2500)


def fingerprint(path: Path) -> str:
    digest = hashlib.sha256()
    digest.update(path.read_bytes())
    digest.update(f"webp-v1:{PHOTO_QUALITY}:{MEDICAL_QUALITY}:{ENCODER_METHOD}".encode())
    return digest.hexdigest()


def save_webp(image: Image.Image, target: Path, width: int) -> None:
    if width == image.width:
        output = image
    else:
        height = max(1, round(image.height * width / image.width))
        output = image.resize((width, height), Image.Resampling.LANCZOS)

    quality = MEDICAL_QUALITY if "-illu" in target.stem else PHOTO_QUALITY
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(target.suffix + ".tmp")
    try:
        output.save(temporary, format="WEBP", quality=quality, method=ENCODER_METHOD)
        with Image.open(temporary) as check:
            check.verify()
        with Image.open(temporary) as check:
            if check.size != output.size:
                raise ValueError(f"Incorrect output size: {target}")
        temporary.replace(target)
    finally:
        temporary.unlink(missing_ok=True)


def to_safe_mode(image: Image.Image) -> Image.Image:
    image = ImageOps.exif_transpose(image)
    if image.mode == "P":
        image = image.convert("RGBA" if "transparency" in image.info else "RGB")
    elif image.mode not in ("RGB", "RGBA"):
        image = image.convert("RGBA" if "A" in image.getbands() else "RGB")
    if image.mode == "RGBA" and image.getchannel("A").getextrema() == (255, 255):
        image = image.convert("RGB")
    return image


def build_module(records: list[dict]) -> str:
    imports: list[str] = []
    lines = [
        "// Generated by scripts/optimize-images.py. Do not edit by hand.",
        "export type ImageInfo = { width: number; height: number; variants: { width: number; url: string }[] };",
    ]
    for index, record in enumerate(records):
        imports.append(
            f'import defaultAsset{index} from '
            f'{json.dumps("./images/" + record["stem"] + ".webp", ensure_ascii=False)};'
        )
        for width in record["variants"]:
            variable = f"variant{index}w{width}"
            file_name = f'{record["stem"]}-w{width}.webp'
            imports.append(f'import {variable} from {json.dumps("./images/" + file_name, ensure_ascii=False)};')
    lines = imports + [""] + lines + ["", "export const imageData: Record<string, ImageInfo> = {"]
    for index, record in enumerate(records):
        variants = ", ".join(
            f'{{ width: {width}, url: variant{index}w{width} }}' for width in record["variants"]
        )
        lines.append(
            f'  {json.dumps(record["key"], ensure_ascii=False)}: '
            f'{{ width: {record["width"]}, height: {record["height"]}, variants: [{variants}] }},'
        )
    lines.append("};")
    lines.extend(["", "export const imageDataByUrl: Record<string, ImageInfo> = {"])
    for index, record in enumerate(records):
        lines.append(
            f'  [defaultAsset{index}]: imageData[{json.dumps(record["key"], ensure_ascii=False)}],'
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    if not features.check("webp"):
        raise RuntimeError("This Pillow installation has no WebP encoder")

    active_names = active_webp_names()
    if not SOURCE_DIR.is_dir():
        missing = sorted(name for name in active_names if not (OUTPUT_DIR / name).is_file())
        if missing or not OUTPUT_MODULE.is_file():
            raise FileNotFoundError(
                f"Archived sources are unavailable and active WebP assets or metadata are missing: {missing}"
            )
        print("Archived PNG/JPEG sources are unavailable; keeping existing WebP assets and metadata")
        return
    sources = sorted(
        (path for path in SOURCE_DIR.iterdir()
         if path.suffix.lower() in INPUT_SUFFIXES and f"{slug(path.stem)}.webp" in active_names),
        key=lambda path: path.name.casefold(),
    )
    missing = active_names - {f"{slug(path.stem)}.webp" for path in sources}
    if missing:
        raise ValueError(f"Missing archived sources for active images: {sorted(missing)}")
    names = [slug(path.stem) for path in sources]
    if any(not name for name in names) or len(set(names)) != len(names):
        raise ValueError("Empty or duplicate normalized image name; fix inputs before writing")

    old_state = json.loads(STATE_FILE.read_text(encoding="utf-8")) if STATE_FILE.exists() else {}
    new_state: dict[str, str] = {}
    records: list[dict] = []
    created = 0
    reused = 0
    original_bytes = 0
    output_bytes = 0

    for path, name in zip(sources, names):
        with Image.open(path) as source:
            image = to_safe_mode(source)
            width, height = image.size
            variants = [w for w in RESPONSIVE_WIDTHS if w < width] if use_responsive_sizes(path, width) else []
            outputs = [(width, OUTPUT_DIR / f"{name}.webp")]
            outputs += [(w, OUTPUT_DIR / f"{name}-w{w}.webp") for w in variants]
            source_key = path.name
            source_fingerprint = fingerprint(path)
            new_state[source_key] = source_fingerprint
            changed = old_state.get(source_key) != source_fingerprint
            for output_width, target in outputs:
                if changed or not target.exists():
                    save_webp(image, target, output_width)
                    created += 1
                else:
                    with Image.open(target) as existing:
                        existing.verify()
                    reused += 1
                output_bytes += target.stat().st_size

        original_bytes += path.stat().st_size
        records.append({"key": path.stem, "stem": name, "width": width, "height": height, "variants": variants})

    module = build_module(records)
    if not OUTPUT_MODULE.exists() or OUTPUT_MODULE.read_text(encoding="utf-8") != module:
        OUTPUT_MODULE.write_text(module, encoding="utf-8")
    state_text = json.dumps(new_state, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    if not STATE_FILE.exists() or STATE_FILE.read_text(encoding="utf-8") != state_text:
        STATE_FILE.write_text(state_text, encoding="utf-8")

    print(f"Sources: {len(sources)}; generated/replaced: {created}; reused: {reused}")
    print(f"Source bytes: {original_bytes:,}; WebP bytes (all outputs): {output_bytes:,}")
    print(f"Responsive images: {sum(bool(r['variants']) for r in records)}")
    print(f"Metadata: {OUTPUT_MODULE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
