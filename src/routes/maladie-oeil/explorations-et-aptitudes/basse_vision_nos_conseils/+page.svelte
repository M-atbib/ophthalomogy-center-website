	<Title level="h1">Basse vision : nos conseils</Title>

	<Text>
		Le terme "Basse Vision" ne renvoie pas à la cécité totale, mais concerne plutôt les situations
		pathologiques qui entraînent une déficience visuelle (acuité visuelle du meilleur œil inférieure
		à 4/10ème et/ou champ visuel inférieur à 60°).
	</Text>

	<Title level="h3">Les professionnels de la basse vision</Title>

	<Text>
		L’accompagnement des personnes déficientes visuelles n’est pas simple et nécessite
		l’intervention de différents acteurs. Leurs rôles respectifs sont complémentaires et
		s’articulent pour mener une prise en charge globale. Un patient atteint de déficience visuelle
		conserve, le plus souvent, une fonction visuelle résiduelle, dont l'exploitation peut nécessiter
		un apprentissage. De même, des stratégies de compensation sensorielle et des dispositifs
		techniques sont de précieux outils pour faciliter la vie quotidienne ou professionnelle.
	</Text>

	<ul class="mt-2 mb-6 list-disc space-y-2 pl-5">
		<li>
			Ophtalmologiste : C'est votre référent principal, votre interlocuteur priviligié quant à la
			santé visuelle. Il est à l’initiative du projet de réadaptation. En sa qualité de médecin,
			c'est lui qui pose le diagnostic et propose un traitement adéquat, si celui-ci existe. Il vous
			oriente également vers d'autres professionnels à même de vous aider ; c'est lui, par exemple,
			qui prescrit la réalisation de séances de rééducation orthoptique.
		</li>
		<li>
			Orthoptiste : Après prescription médicale, l'orthoptiste peut débuter une rééducation
			en plusieurs séances. Par des exercices ciblés, il permet, par exemple, l'apprentissage de
			l'optimisation visuelle, par des stratégies de décentrement du regard (efficace en cas de
			maculopathie invalidante).
		</li>
		<li>
			Opticien spécialisé en basse vision : Il pourra fournir des dispositifs techniques
			grossissants, des écrans et autres télé-agrandisseurs. Il convient, le plus souvent, de tester
			le matériel avant l'achat ; l'opticien est évidemment un partenaire essentiel pour ce faire.
		</li>
		<li>Psychologue : C’est un soutien indéniable dans le processus d’acceptation du handicap.</li>
		<li>
			Instructeur en locomotion : Il permet d’être davantage autonome dans les déplacements
			extérieurs.
		</li>
		<li>
			Instructeur en autonomie de la vie journalière : Il permet de retrouver un maximum d’autonomie
			dans l’ensemble des gestes de la vie quotidienne (soins, activités domestiques, loisirs, vie
			en société…).
		</li>
		<li>
			Ergothérapeute : Son expertise est essentielle concernant les aides matérielles possibles et
			l’aménagement de l’environnement quotidien.
		</li>
	</ul>

	<Title level="h3">Les dispositifs d'aide visuelle</Title>

	<Text>
		De nombreuses aides optiques existent ; elles sont encore peu connues du grand public. Onéreuses
		pour la plupart, elles sont néanmoins l'objets d'innovations techniques régulières. Pour ces
		raisons, il est indispensable d’être bien conseillé avant de procéder à un achat. Les
		spécialistes cités plus haut pourront vous aider à faire le meilleur choix.
	</Text>

	<ul class="mt-2 mb-6 list-disc space-y-2 pl-5">
		<li>
			Les lampes : Un bon éclairage favorise une bonne vision des contrastes et permet d'améliore
			l'acuité visuelle. Une lampe efficace doit permettre d’orienter l’éclairage et de faire varier
			l’intensité lumineuse.
		</li>
		<li>
			Les filtres protecteurs : Ils limitent l’éblouissement, filtrent les UVs et renforcent la
			perception des contrastes.
		</li>
		<li>
			Les lunettes grossissantes : Ce sont des paires de lunettes de forte puissance pour une
			meilleure vision de près.
		</li>
		<li>
			Les loupes grossissantes : Elles permettent de grossir un texte ou un objet. Il en existe une
			multitude sur le marché, adaptées à différents usages (loupe avec manche, à poser, à adapter
			sur des montures de lunettes, avec lampe intégrée…). Un conseil et un essai sont nécessaires
			avant achat.
		</li>
		<li>
			Les systèmes télescopiques : Ils nécessitent l’association d’au moins deux lentilles (le plus
			souvent une divergente et une convergente) qui permettront d’agrandir une image, plutôt en
			vision de loin.
		</li>
		<li>
			Les systèmes électroniques : loupes électroniques et télé-agrandisseurs. Ils permettent de
			regarder l’image agrandie sur un écran. Les loupes sont de petite taille et facilement
			transportables, mais les télé-agrandisseurs permettent un fort grossissement avec un champ de
			vision plus important. Les systèmes électroniques ont l’avantage de pouvoir choisir différents
			paramètres, dont la luminosité, les contrastes, la taille de grossissement… Ces dispositifs
			disposent des innovations technologiques et informatique les plus récentes. Par exemple,
			certains appareils intègrent désormais une fonction de synthèse vocale.
		</li>
		<li>
			Les tablettes tactiles sont des objets du quotidien. Des fonctions et/ou applications sont
			disponibles pour les transformer en dispositifs d'aide visuelle.
		</li>
	</ul>

	<Title level="h3">Nos conseils</Title>
	<Text>
		Si vous souffrez de déficience visuelle et éprouvez des difficultés dans votre vie
		quotidienne, ne vous découragez pas. Ces quelques conseils peuvent vous aider à conserver une
		certaine qualité de vie, en dépit de votre handicap.
	</Text>
	<Title level="sub2">Gardez confiance en vous et en votre capacité à vous adapter</Title>
	<Text>
		Aucune difficulté n’est insurmontable et de nombreux dispositifs d’aide visuelle permettent
		aujourd’hui de conserver la meilleure autonomie et la meilleure qualité de vie possibles. Enfin,
		sachez que votre corps garde en mémoire des gestes et des lieux familiers. Essayez d’oublier un
		instant votre handicap visuel, et vous serez surpris de constater que vous êtes toujours capable
		d’effectuer, par instinct, certaines activités auxquelles vous aviez pourtant renoncé.
	</Text>
	<Title level="sub2">Appuyez-vous sur votre entourage</Title>
	<Text>
		Dites clairement à vos proches quel type d’aide vous attendez idéalement d’eux. Cela évitera bon
		nombre de malentendus et leur épargnera la tentation de tout faire à votre place.
	</Text>
	<Title level="sub2">N’ayez pas peur d’utiliser vos yeux</Title>
	<Text>
		Les solliciter n’entraînera en aucun cas une aggravation de votre handicap visuel. Bien au
		contraire, l’œil doit être entraîné pour rester efficace.
	</Text>
	<Title level="sub2">
		N’hésitez pas à utiliser un éclairage d’appoint pour réaliser des activités nécessitant une
		vision des détails ou à vous rapprocher de votre poste de télévision
	</Title>
	<Text>
		Ce rapprochement vous apportera un grossissement naturel de l’image. Il est sans danger pour vos
		yeux !
	</Text>
	<Title level="sub2">Faites-vous conseiller par un spécialiste de la basse vision</Title>
	<Text>
		Il vous aidera à mieux vivre votre handicap au quotidien et à identifier les dispositifs d’aide
		visuelle les plus adaptés à vos capacités et à vos besoins.
	</Text>
	<Title level="h3">Pour aller plus loin</Title>
